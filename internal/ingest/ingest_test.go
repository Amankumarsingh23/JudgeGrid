type fixture struct {
	dir string
	t   *testing.T
}

func newFixture(t *testing.T, format string) *fixture {
	t.Helper()
	f := &fixture{filepath.Join(t.TempDir(), "repo"), t}
	if e := os.Mkdir(f.dir, 0700); e != nil {
		t.Fatal(e)
	}
	f.git(nil, "init", "--object-format="+format, "--initial-branch=main")
	f.git(nil, "config", "core.autocrlf", "false")
	return f
}
func (f *fixture) git(input []byte, args ...string) string {
	f.t.Helper()
	cmd := exec.Command("git", append([]string{"-c", "core.hooksPath=" + os.DevNull, "-c", "commit.gpgSign=false", "-C", f.dir}, args...)...)
	cmd.Env = append(gitEnv(), "GIT_AUTHOR_NAME=Fixture", "GIT_AUTHOR_EMAIL=fixture@example.invalid", "GIT_COMMITTER_NAME=Fixture", "GIT_COMMITTER_EMAIL=fixture@example.invalid", "GIT_AUTHOR_DATE=2026-01-01T00:00:00Z", "GIT_COMMITTER_DATE=2026-01-01T00:00:00Z")
	cmd.Stdin = bytes.NewReader(input)
	b, e := cmd.CombinedOutput()
	if e != nil {
		f.t.Fatalf("fixture git %s failed: %v %s", args[0], e, b)
	}
	return strings.TrimSpace(string(b))
}
func (f *fixture) write(p, body string) {
	f.t.Helper()
	name := filepath.Join(f.dir, filepath.FromSlash(p))
	if e := os.MkdirAll(filepath.Dir(name), 0700); e != nil {
		f.t.Fatal(e)
	}
	if e := os.WriteFile(name, []byte(body), 0600); e != nil {
		f.t.Fatal(e)
	}
}
func (f *fixture) commit() string {
	f.git(nil, "add", ".")
	f.git(nil, "commit", "--allow-empty", "-m", "fixture")
	return f.git(nil, "rev-parse", "HEAD")
}
func (f *fixture) open(t *testing.T) *Git {
	t.Helper()
	g, e := OpenGit(context.Background(), Trust{Roots: []string{filepath.Dir(f.dir)}}, f.dir)
	if e != nil {
		t.Fatal(e)
	}
	t.Cleanup(g.Close)
	return g
}

func TestIngestionPolicyAndPathBoundaries(t *testing.T) {
	if classify([]byte("version https://git-lfs.github.com/spec/v1\r\noid sha256:fixture\r\nsize 1\r\n"), "go") != "lfs_pointer" {
		t.Fatal("CRLF LFS pointer treated as source")
	}
	p := DefaultPolicy()
	if e := p.Validate(); e != nil {
		t.Fatal(e)
	}
	q := p
	q.Docs = false
	if p.ID() == q.ID() {
		t.Fatal("policy collision")
	}
	for _, path := range []string{"../a.go", "a/../b.go", "/abs.go", "a\\b.go", "a:b.go", ".git/config", "a//b.go", "a./b.go", "NUL.go", "a/COM1.txt", "e\u0301.go", string([]byte{255}) + ".go", "a\u202eb.go"} {
		if validPath(path) {
			t.Fatalf("unsafe path accepted: %q", path)
		}
	}
	for _, path := range []string{"a/b.go", "é.go", ".github/workflows/ci.yml"} {
		if !validPath(path) {
			t.Fatal("safe UTF-8 path refused", path)
		}
	}
	for _, mutate := range []func(*Policy){func(p *Policy) { p.MaxEntries = 20001 }, func(p *Policy) { p.MaxDepth = 65 }, func(p *Policy) { p.MaxFiles = 5001 }, func(p *Policy) { p.MaxFileBytes = 3 << 20 }, func(p *Policy) { p.MaxTotalBytes = 33 << 20 }, func(p *Policy) { p.MaxSeconds = 301 }, func(p *Policy) { p.ParallelReads = 2 }, func(p *Policy) { p.Version = "unknown" }} {
		x := p
		mutate(&x)
		if x.Validate() == nil {
			t.Fatal("unbounded policy accepted")
		}
	}
	for _, v := range []struct{ path, lang, reason string }{{"main.go", "go", "included"}, {"main.py", "python", "included"}, {"X.java", "java", "included"}, {"a.cpp", "cpp", "included"}, {"a.tsx", "typescript", "included"}, {"Dockerfile", "dockerfile", "included"}, {".env.local", "", "sensitive_path"}, {"node_modules/a.js", "", "dependency_build"}, {"app.min.js", "", "generated_minified"}, {"x.exe", "", "unsupported_type"}} {
		lang, reason := selectPath(v.path, true)
		if lang != v.lang || reason != v.reason {
			t.Fatal(v, lang, reason)
		}
	}
	for _, v := range []struct{ body, reason string }{{"hello", "included"}, {"a\x00b", "binary"}, {string([]byte{255}), "encoding"}, {"version https://git-lfs.github.com/spec/v1\noid sha256:abc\nsize 1\n", "lfs_pointer"}, {"-----BEGIN PRIVATE KEY-----\nfixture\n", "secret_evidence"}, {"api_key = \"only_a_synthetic_test_credential\"", "secret_evidence"}, {"// Code generated by fixture. DO NOT EDIT.\n", "generated_minified"}} {
		if got := classify([]byte(v.body), "go"); got != v.reason {
			t.Fatal(v.reason, got)
		}
	}
}
func TestGitObjectPinningFormatsAndUnsafeConfig(t *testing.T) {
	for _, format := range []string{"sha1", "sha256"} {
		t.Run(format, func(t *testing.T) {
			f := newFixture(t, format)
			f.write("main.go", "package original\n")
			a := f.commit()
			g := f.open(t)
			commit, tree, e := g.Resolve("HEAD")
			if e != nil || commit != a {
				t.Fatal(e)
			}
			f.git(nil, "tag", "-a", "v1", "-m", "fixture tag", a)
			f.git(nil, "pack-refs", "--all")
			if tagCommit, tagTree, e := g.Resolve("refs/tags/v1"); e != nil || tagCommit != a || tagTree != tree {
				t.Fatal("packed annotated tag resolution", e)
			}
			f.write("main.go", "package changed\n")
			f.commit()
			f.write("main.go", "dirty working tree\n")
			marker := filepath.Join(f.dir, "executed-marker")
			f.git(nil, "config", "filter.evil.smudge", "touch "+marker)
			f.git(nil, "config", "core.fsmonitor", "touch "+marker)
			f.write(".gitattributes", "*.go filter=evil\n")
			oid := f.git([]byte("replacement"), "hash-object", "-w", "--stdin")
			original := f.git(nil, "rev-parse", a+":main.go")
			f.git(nil, "replace", original, oid)
			entries, e := g.Inventory(context.Background(), tree, DefaultPolicy())
			if e != nil || len(entries) != 1 {
				t.Fatal(entries, e)
			}
			b, e := g.Read(entries[0].OID, "blob", 1024)
			if e != nil || string(b) != "package original\n" {
				t.Fatal("moving branch, dirty tree, replacement or filter affected bytes", e)
			}
			if objectOID(format, "blob", b) != original || Digest(b) == original {
				t.Fatal("Git and raw byte hashes conflated")
			}
			if _, e = os.Stat(marker); !errors.Is(e, os.ErrNotExist) {
				t.Fatal("repository command executed")
			}
			if _, _, e = g.Resolve(strings.Repeat("f", len(a))); e == nil {
				t.Fatal("missing commit substituted")
			}
			if _, _, e = g.Resolve("--exec=evil"); e == nil {
				t.Fatal("revision option accepted")
			}
		})
	}
}
func TestGitSpecialEntriesAndBudgets(t *testing.T) {
	f := newFixture(t, "sha1")
	if bad, e := OpenGit(context.Background(), Trust{Roots: []string{t.TempDir()}}, f.dir); !errors.Is(e, ErrDenied) {
		if bad != nil {
			bad.Close()
		}
		t.Fatal("unapproved local root accepted", e)
	}
	f.write("a.go", "package a\n")
	commit := f.commit()
	symlink := f.git([]byte("../../host-private-file"), "hash-object", "-w", "--stdin")
	f.git(nil, "update-index", "--add", "--cacheinfo", "120000,"+symlink+",escape.go")
	f.git(nil, "update-index", "--add", "--cacheinfo", "160000,"+commit+",module")
	f.git(nil, "commit", "-m", "special entries")
	g := f.open(t)
	_, tree, e := g.Resolve("HEAD")
	if e != nil {
		t.Fatal(e)
	}
	items, e := g.Inventory(context.Background(), tree, DefaultPolicy())
	if e != nil {
		t.Fatal(e)
	}
	reasons := map[string]string{}
	for _, v := range items {
		reasons[v.Path] = v.Reason
	}
	if reasons["escape.go"] != "symlink" || reasons["module"] != "gitlink" {
		t.Fatal(reasons)
	}
	p := DefaultPolicy()
	p.MaxEntries = 1
	if _, e = g.Inventory(context.Background(), tree, p); !errors.Is(e, ErrBudget) {
		t.Fatal("entry cap", e)
	}
	p = DefaultPolicy()
	p.MaxPathBytes = 1
	if _, e = g.Inventory(context.Background(), tree, p); !errors.Is(e, ErrBudget) {
		t.Fatal("combined path-byte cap", e)
	}
	f.write("deep/a/b/c.go", "package c\n")
	f.commit()
	g2 := f.open(t)
	_, tree, e = g2.Resolve("HEAD")
	if e != nil {
		t.Fatal(e)
	}
	p = DefaultPolicy()
	p.MaxDepth = 2
	if _, e = g2.Inventory(context.Background(), tree, p); !errors.Is(e, ErrBudget) {
		t.Fatal("depth cap", e)
	}
	if _, e = g2.Read(f.git(nil, "rev-parse", "HEAD:a.go"), "blob", 1); !errors.Is(e, ErrBudget) {
		t.Fatal("blob cap", e)
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if _, e = g2.Inventory(ctx, tree, DefaultPolicy()); !errors.Is(e, context.Canceled) {
		t.Fatal("cancellation", e)
	}
}
func TestGitMalformedAndAliasedPathsFailClosed(t *testing.T) {
	for _, names := range [][]string{{"../escape.go"}, {string([]byte{255}) + ".go"}, {"A.go", "a.go"}, {"e\u0301.go"}} {
		t.Run(fmt.Sprintf("%x", names), func(t *testing.T) {
			f := newFixture(t, "sha1")
			f.write("ok.go", "package ok\n")
			f.commit()
			blob := f.git(nil, "rev-parse", "HEAD:ok.go")
			rawOID, _ := hex.DecodeString(blob)
			raw := []byte{}
			for _, name := range names {
				raw = append(raw, []byte("100644 "+name+"\x00")...)
				raw = append(raw, rawOID...)
			}
			tree := f.git(raw, "hash-object", "--literally", "-t", "tree", "-w", "--stdin")
			commit := f.git([]byte("tree "+tree+"\nauthor Fixture <fixture@example.invalid> 1 +0000\ncommitter Fixture <fixture@example.invalid> 1 +0000\n\nfixture\n"), "hash-object", "-t", "commit", "-w", "--stdin")
			g := f.open(t)
			_, tree, e := g.Resolve(commit)
			if e != nil {
				t.Fatal(e)
			}
			if _, e = g.Inventory(context.Background(), tree, DefaultPolicy()); e == nil {
				t.Fatal("ambiguous path accepted")
			}
		})
	}
}
func TestRootedImmutableContentStore(t *testing.T) {
	s, e := OpenLocal(t.TempDir())
	if e != nil {
		t.Fatal(e)
	}
	defer s.Close()
	ctx := context.Background()
	repo := "11111111-1111-4111-8111-111111111111"
	for _, b := range [][]byte{nil, []byte("private fixture")} {
		key := blobKey(repo, Digest(b))
		for range 2 {
			if e = s.Put(ctx, key, b); e != nil {
				t.Fatal(e)
			}
		}
		got, e := s.Get(ctx, key, int64(len(b)))
		if e != nil || !bytes.Equal(got, b) {
			t.Fatal(e)
		}
	}
	if e = s.Put(ctx, "../escape", []byte("bad")); !errors.Is(e, ErrIntegrity) {
		t.Fatal(e)
	}
	b := []byte("private fixture")
	key := blobKey(repo, Digest(b))
	if e = s.root.WriteFile(key, []byte("corrupt"), 0600); e != nil {
		t.Fatal(e)
	}
	if _, e = s.Get(ctx, key, 100); !errors.Is(e, ErrIntegrity) {
		t.Fatal("corrupt content accepted", e)
	}
	if e = s.Put(ctx, key, b); !errors.Is(e, ErrIntegrity) {
		t.Fatal("published object overwritten", e)
	}
	outside := filepath.Join(t.TempDir(), "outside")
	if e = os.WriteFile(outside, []byte("outside"), 0600); e != nil {
		t.Fatal(e)
	}
	link := blobKey(repo, Digest([]byte("outside")))
	if e = s.root.Symlink(outside, link); e != nil {
		t.Fatal(e)
	}
	if _, e = s.Get(ctx, link, 100); e == nil {
		t.Fatal("root escape followed")
	}
	if _, e = s.Inventory(ctx, repo, 1); !errors.Is(e, ErrBudget) {
		t.Fatal("local inventory did not stop under entry budget", e)
	}
}
func TestRemoteApprovalAndBoundedBroker(t *testing.T) {
	trust := Trust{Origins: []string{"https://github.com/owner/repo.git"}}
	for _, s := range []string{"file:///tmp/a", "ssh://git@github.com/owner/repo", "https://u:p@github.com/owner/repo.git", "https://127.0.0.1/a/b", "https://localhost/a/b", "https://github.com/owner/repo.git?x=1", "https://github.com.evil/a/b", "https://github.com/owner/../repo", "https://github.com/owner/repo.git#token"} {
		if trust.Remote(s) {
			t.Fatal("unapproved origin", s)
		}
	}
	if !trust.Remote(trust.Origins[0]) {
		t.Fatal("approved origin refused")
	}
	for _, s := range []string{"127.0.0.1", "169.254.169.254", "10.0.0.1", "100.64.0.1", "::1", "::ffff:127.0.0.1", "2001:db8::1", "64:ff9b::c0a8:1", "fec0::1"} {
		if publicAddress(netip.MustParseAddr(s)) {
			t.Fatal("nonpublic IP", s)
		}
	}
	for _, s := range []string{"1.1.1.1", "8.8.8.8", "2606:4700:4700::1111"} {
		if !publicAddress(netip.MustParseAddr(s)) {
			t.Fatal("public IP refused")
		}
	}
	u, _ := url.Parse(trust.Origins[0])
	budget := &fetchBudget{}
	budget.remaining.Store(32)
	upstream := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { w.Write([]byte(strings.Repeat("x", 100))) }))
	defer upstream.Close()
	target, _ := url.Parse(upstream.URL)
	client := upstream.Client()
	handler := broker(context.Background(), target, client, budget)
	w := httptest.NewRecorder()
	handler.ServeHTTP(w, httptest.NewRequest("GET", "/other", nil))
	if w.Code != 400 {
		t.Fatal("unapproved transport path")
	}
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, httptest.NewRequest("GET", "/info/refs?service=git-upload-pack", nil))
	if w.Code != 413 {
		t.Fatal("unbounded response accepted", w.Code)
	}
	_ = u
}
func TestApprovedSmartHTTPFetchUsesOnlyObjects(t *testing.T) {
	f := newFixture(t, "sha1")
	f.write("main.go", "package fetched\n")
	commit := f.commit()
	git, e := exec.LookPath("git")
	if e != nil {
		t.Fatal(e)
	}
	handler := &cgi.Handler{Path: git, Args: []string{"http-backend"}, Dir: filepath.Dir(f.dir), Env: append(gitEnv(), "GIT_PROJECT_ROOT="+filepath.Dir(f.dir), "GIT_HTTP_EXPORT_ALL=1")}
	server := httptest.NewTLSServer(handler)
	defer server.Close()
	u, _ := url.Parse(server.URL + "/repo/.git")
	mirror := t.TempDir()
	trust := Trust{Roots: []string{mirror}}
	if e = InitializeMirror(mirror, "sha1", trust); e != nil {
		t.Fatal(e)
	}
	g, e := OpenGit(context.Background(), trust, mirror)
	if e != nil {
		t.Fatal(e)
	}
	defer g.Close()
	var diagnostics bytes.Buffer
	g.diagnostic = &diagnostics
	oid, e := g.fetchUsing(context.Background(), u, "refs/heads/main", server.Client())
	if e != nil {
		t.Fatal(e, diagnostics.String())
	}
	got, tree, e := g.Resolve(oid)
	if e != nil || got != commit {
		t.Fatal("fetch did not pin actual commit", got, e)
	}
	entries, e := g.Inventory(context.Background(), tree, DefaultPolicy())
	if e != nil || len(entries) != 1 {
		t.Fatal(entries, e)
	}
	b, e := g.Read(entries[0].OID, "blob", 1024)
	if e != nil || string(b) != "package fetched\n" {
		t.Fatal(e)
	}
	firstBytes := g.RemoteBytes
	f.write("new.ts", "export const added=1;\n")
	next := f.commit()
	if e = g.seedHaves([]string{commit}); e != nil {
		t.Fatal(e)
	}
	oid, e = g.fetchUsing(context.Background(), u, "refs/heads/main", server.Client())
	if e != nil {
		t.Fatal(e, diagnostics.String())
	}
	got, tree, e = g.Resolve(oid)
	if e != nil || got != next {
		t.Fatal("incremental remote target substituted", e)
	}
	entries, e = g.Inventory(context.Background(), tree, DefaultPolicy())
	if e != nil || len(entries) != 2 {
		t.Fatal("incremental remote inventory incomplete", e)
	}
	t.Logf("bounded HTTPS Git response-body bytes: initial=%d following=%d (not a general bandwidth gain claim)", firstBytes, g.RemoteBytes)
	// A missing requested commit must fail instead of fetching a different branch.
	if _, e = g.fetchUsing(context.Background(), u, strings.Repeat("f", 40), server.Client()); e == nil {
		t.Fatal("missing remote SHA substituted")
	}
}
